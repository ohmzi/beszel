"""scaffold: `homelab-maint new task|job|probe NAME` generators and SECURE plugin discovery (SPEC4 S11).

GENERATORS (render_* are pure; create() writes)
  new task NAME   a ready-to-edit task module (C0 read-only | C1 safe cleaner through ctx.act | C2 plan + approval) and a test stub
  new job NAME    a jobs.toml [[job]] snippet (an external command the scheduler runs, gates, logs and reports)
  new probe NAME  a probes.toml [[probe]] snippet (http | tcp | docker | systemd | command | file_age | json)
  Nothing is written outside --out unless --install, which targets <conf>/plugins.d (tasks), <conf>/jobs.d and <conf>/probes.d
  (snippets) and is REFUSED when this build's loader does not read that directory (loader_reads: a file nothing picks up would look
  installed and never run). Files are created O_EXCL|O_NOFOLLOW (never overwrite, never follow a planted symlink), names are validated,
  and every generated Python file is compiled and every TOML snippet parsed before it is written, so what you get always loads (the
  tests also load every generated job and probe through the real scheduler and probe engine).

PLUGIN DISCOVERY (load_plugins; the glue calls it from cli.load_tasks)
  /etc/homelab-maint/plugins.d/*.py are ROOT CODE: whoever can write there owns the box. So a plugin is executed only when
    * the directory (and every ancestor) is a real directory owned by root (or the runner), not group/world-writable
      (sticky dirs such as /tmp are tolerated as ancestors only),
    * the file is a regular file (a symlink is refused even if root-owned), owned by root (or the runner), not group/world
      writable, <= 256 KiB, with a plain module-name file name,
    * the bytes that are compiled are the bytes of the file descriptor that passed those checks (O_NOFOLLOW, fstat compared with
      lstat: no check-then-open race).
  A plugin is isolated: its import is guarded by a timeout, any exception (SyntaxError, ImportError, SystemExit, a hung import)
  rolls back whatever it registered and is reported as a registered `plugin_<stem>` task whose result is `error`, so the owner
  sees it in status.json and gets paged, and every other plugin and builtin still runs. A plugin can never REPLACE or remove a
  builtin task (the registry entry is restored and the attempt is reported), and registered tasks are validated (name, class,
  tier, callable, timeout) before they are kept. An insecure directory refuses all plugins and registers `plugins_dir`.
"""
